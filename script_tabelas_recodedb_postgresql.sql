-- Esquema PostgreSQL para o Portal de Gestao Educacional.
-- Execute conectado ao banco recodedatabase. Este script recria as tabelas.
-- As tabelas e colunas correspondem aos mapeamentos JPA atuais do backend.

BEGIN;

DROP TABLE IF EXISTS progressosalunos CASCADE;
DROP TABLE IF EXISTS pedidos CASCADE;
DROP TABLE IF EXISTS matriculas CASCADE;
DROP TABLE IF EXISTS enderecosescolas CASCADE;
DROP TABLE IF EXISTS enderecosalunos CASCADE;
DROP TABLE IF EXISTS avaliacoesqualidade CASCADE;
DROP TABLE IF EXISTS avaliacoescursos CASCADE;
DROP TABLE IF EXISTS avaliacoesalunos CASCADE;
DROP TABLE IF EXISTS alunos CASCADE;
DROP TABLE IF EXISTS cursos CASCADE;
DROP TABLE IF EXISTS produtos CASCADE;
DROP TABLE IF EXISTS professores CASCADE;
DROP TABLE IF EXISTS escolas CASCADE;

CREATE TABLE escolas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 52) PRIMARY KEY,
    nome VARCHAR(255) NOT NULL,
    email VARCHAR(255),
    telefone VARCHAR(255),
    tipo VARCHAR(255) NOT NULL
);

CREATE TABLE professores (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 2) PRIMARY KEY,
    nome VARCHAR(255) NOT NULL,
    email VARCHAR(255),
    telefone VARCHAR(255),
    especialidade VARCHAR(255),
    biografia VARCHAR(1000),
    escolaid BIGINT REFERENCES escolas (id)
);

CREATE TABLE cursos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 51) PRIMARY KEY,
    nome VARCHAR(255) NOT NULL,
    descricao VARCHAR(1000),
    carga_horaria INTEGER,
    escolaid BIGINT NOT NULL REFERENCES escolas (id),
    professorid BIGINT REFERENCES professores (id),
    preco NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
    nivelensino VARCHAR(20) NOT NULL DEFAULT 'capacitacao'
        CHECK (nivelensino IN ('basico', 'tecnico', 'superior', 'capacitacao')),
    gratuito BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE alunos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 51) PRIMARY KEY,
    area VARCHAR(10) NOT NULL CHECK (area IN ('urbana', 'rural')),
    distancia_escola NUMERIC(5, 2),
    tipo_transporte VARCHAR(30)
        CHECK (tipo_transporte IN ('a_pe', 'transporte_escolar', 'transporte_publico', 'proprio')),
    tempo_deslocamento_minutos INTEGER,
    cursoid BIGINT REFERENCES cursos (id),
    escolaid BIGINT REFERENCES escolas (id)
);

CREATE TABLE avaliacoesalunos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 51) PRIMARY KEY,
    data_avaliacao DATE,
    nota DOUBLE PRECISION NOT NULL,
    observacao VARCHAR(500),
    aluno_id BIGINT NOT NULL REFERENCES alunos (id),
    curso_id BIGINT NOT NULL REFERENCES cursos (id)
);

CREATE TABLE avaliacoescursos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nota DOUBLE PRECISION NOT NULL CHECK (nota BETWEEN 0 AND 10),
    observacao VARCHAR(500),
    data_avaliacao DATE,
    curso_id BIGINT NOT NULL REFERENCES cursos (id)
);

CREATE TABLE avaliacoesqualidade (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 51) PRIMARY KEY,
    comentario VARCHAR(500),
    data_avaliacao DATE,
    nota INTEGER NOT NULL CHECK (nota BETWEEN 1 AND 5),
    escola_id BIGINT NOT NULL REFERENCES escolas (id)
);

CREATE TABLE enderecosalunos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 2) PRIMARY KEY,
    cep VARCHAR(9),
    logradouro VARCHAR(255) NOT NULL,
    numero VARCHAR(255),
    bairro VARCHAR(255),
    cidade VARCHAR(255) NOT NULL,
    estado VARCHAR(2) NOT NULL,
    aluno_id BIGINT NOT NULL REFERENCES alunos (id)
);

CREATE TABLE enderecosescolas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 51) PRIMARY KEY,
    cep VARCHAR(9),
    logradouro VARCHAR(255) NOT NULL,
    numero VARCHAR(255),
    bairro VARCHAR(255),
    cidade VARCHAR(255) NOT NULL,
    estado VARCHAR(2) NOT NULL,
    tipo_localizacao VARCHAR(10) NOT NULL DEFAULT 'urbana'
        CHECK (tipo_localizacao IN ('urbana', 'rural')),
    latitude NUMERIC(10, 8),
    longitude NUMERIC(11, 8),
    formatted_address VARCHAR(500),
    escolaid BIGINT NOT NULL UNIQUE REFERENCES escolas (id)
);

CREATE TABLE matriculas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alunoid BIGINT NOT NULL REFERENCES alunos (id),
    cursoid BIGINT NOT NULL REFERENCES cursos (id),
    data_matricula TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    valor_pago NUMERIC(10, 2) NOT NULL,
    status_pagamento VARCHAR(20) NOT NULL DEFAULT 'pendente'
        CHECK (status_pagamento IN ('pago', 'pendente', 'cancelado'))
);

CREATE TABLE produtos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 8) PRIMARY KEY,
    nome VARCHAR(255) NOT NULL,
    descricao VARCHAR(500),
    preco NUMERIC(38, 2) NOT NULL,
    quantidade INTEGER NOT NULL DEFAULT 0,
    icone VARCHAR(100),
    categoria VARCHAR(30) NOT NULL DEFAULT 'material_didatico'
        CHECK (categoria IN ('material_didatico', 'uniforme', 'mobiliario', 'tecnologia'))
);

CREATE TABLE pedidos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 4) PRIMARY KEY,
    escolaid BIGINT NOT NULL REFERENCES escolas (id),
    produtoid BIGINT NOT NULL REFERENCES produtos (id),
    quantidade INTEGER NOT NULL,
    valorunitario NUMERIC(10, 2) NOT NULL,
    valortotal NUMERIC(10, 2)
        GENERATED ALWAYS AS (quantidade * valorunitario) STORED,
    datapedido TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    statuspedido VARCHAR(20) NOT NULL DEFAULT 'processando'
        CHECK (statuspedido IN ('processando', 'enviado', 'entregue', 'cancelado')),
    professorid BIGINT NOT NULL REFERENCES professores (id)
);

CREATE TABLE progressosalunos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 2) PRIMARY KEY,
    alunoid BIGINT NOT NULL REFERENCES alunos (id),
    cursoid BIGINT NOT NULL REFERENCES cursos (id),
    percentual_conclusao INTEGER NOT NULL DEFAULT 0
        CHECK (percentual_conclusao BETWEEN 0 AND 100),
    data_atualizacao TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

COMMIT;
